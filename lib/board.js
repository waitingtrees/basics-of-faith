// The shared board lives in one KV value: {v, notes: {id: {x, y, text}}}.
//
// One key rather than one per note is deliberate. A note is tiny, the board
// is read far more than it is written, and a single value means a reader
// never sees half an update — the cost is that two people writing in the
// same instant can have one write land on a stale copy, which for a team
// moodboard is cheaper than the alternative.

export const KEY = "board";

export const MAX_NOTES = 500;
export const MAX_TEXT = 4000;
export const COORD_LIMIT = 500000;   // keeps a note inside a sane world

export async function readBoard(env) {
  const raw = await env.NOTES.get(KEY);
  if (!raw) return { v: 0, notes: {} };
  try {
    const board = JSON.parse(raw);
    return { v: board.v || 0, notes: board.notes || {} };
  } catch (e) {
    return { v: 0, notes: {} };
  }
}

export async function writeBoard(env, board) {
  board.v = (board.v || 0) + 1;
  await env.NOTES.put(KEY, JSON.stringify(board));
  return board.v;
}

/** Note ids are generated by the page; accept only that shape. */
export function validId(id) {
  return typeof id === "string" && /^[A-Za-z0-9_-]{3,40}$/.test(id);
}

export function clean(body) {
  const num = (v) => {
    const n = Number(v);
    if (!Number.isFinite(n)) return 0;
    return Math.max(-COORD_LIMIT, Math.min(COORD_LIMIT, Math.round(n)));
  };
  return {
    x: num(body.x),
    y: num(body.y),
    text: String(body.text ?? "").slice(0, MAX_TEXT),
  };
}

export function json(body, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
    },
  });
}
